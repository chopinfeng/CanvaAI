import { describe, expect, it } from 'vitest';
import { detectTutorIntent } from '../intent.js';

/**
 * 这张表就是"什么算想被教"的定义。
 * 判断标准：宁可漏判也不误判——把想要答案的人拖进苏格拉底式反问，
 * 比让他多点一次开关烦人得多。
 */

describe('想被一步步教', () => {
  for (const s of [
    '给我讲这道题',
    '讲讲这道题',
    '讲一下这题',
    '这道题怎么做',
    '这道题怎么解',
    '教我做这道题',
    '带我解一下',
    '辅导我一下',
    '一步一步教我',
    // 演练里学生真说出来的那句——早先没识别出来，整场辅导没起来
    '老师，这道题我有点思路但不太确定，您带着我一步步做吧。',
    '带着我一步步走一遍',
    '你带我做一下',
    '一步步来吧',
    '我不会',
    '这题我不懂',
    '看不懂，没思路',
    '引导我做出来',
    '考考我',
    // 拿着一份被扣分的作答来问，是最真实的求辅导场景之一
    '这道题我写了，但被扣了4分。我哪里错了？',
    '我哪里错了',
    '错在哪一步',
    '为什么我这样写不对',
    '帮我看看我的作答',
    '检查一下我的过程',
  ]) {
    it(`「${s}」→ 进入辅导`, () => expect(detectTutorIntent(s)).toBe('enter'));
  }
});

describe('想直接要答案', () => {
  for (const s of [
    '直接告诉我答案',
    '把答案给我',
    '别问了，直接给答案',
    '不用引导，直接说结果',
    '退出辅导',
    '直接告诉我答案吧，我赶时间',
  ]) {
    it(`「${s}」→ 退出辅导`, () => expect(detectTutorIntent(s)).toBe('exit'));
  }
});

describe('不学了，去干别的', () => {
  for (const s of [
    '先不学了',
    '这题先放一放',
    '换个话题',
    '先做别的',
    '帮我画个流程图',
    '我们来设计一个方案',
    '不用管这道题了',
  ]) {
    it(`「${s}」→ 离开辅导`, () => expect(detectTutorIntent(s)).toBe('switch'));
  }

  it('和「要答案」是两回事，说给用户的话也不一样', () => {
    expect(detectTutorIntent('直接告诉我答案')).toBe('exit');
    expect(detectTutorIntent('先不学了')).toBe('switch');
  });
});

describe('不该误判的', () => {
  for (const s of [
    '在这个方块上面加个屋顶',
    '帮我把这几个节点连成流程图',
    '讲讲这个架构图的设计思路',   // 协作画图场景，不是解题
    '这个图怎么画',
    '把这条线画粗一点',
    '你好',
    '',
    '这里再加个窗户',
  ]) {
    it(`「${s}」→ 不切换`, () => expect(detectTutorIntent(s)).toBeNull());
  }
});

describe('退出优先于进入', () => {
  it('"别讲了直接告诉我这道题的答案" 判为退出', () => {
    expect(detectTutorIntent('别讲了，直接告诉我这道题的答案')).toBe('exit');
  });
});

/**
 * 这几条都是演练里真实说过的话。
 *
 * 漏掉一条的代价不是"AI 不理你"——它照样会把题讲完，只是全程不进辅导模式：
 * 不拆题、不判定、不记掌握度，三次 tutor_plan 被闸拦下，理由是
 * "辅导已经结束了"，而它从没开始过。转录看着挺好，记录里什么都没有。
 */
describe('求辅导的说法（真实语料）', () => {
  for (const line of [
    '老师，这题我一点思路都没有。你先带我从第一问开始吧？',
    '带我从第(1)问开始',
    '从第一问开始带我走一遍',
    '从头开始讲吧，我基础不好',
    '你带我入手一下',
    '老师你一步步问我吧，我跟着做',
    '一步步引导我做',
  ]) {
    it(`认得出：${line}`, () => {
      expect(detectTutorIntent(line)).toBe('enter');
    });
  }

  it('不误伤：说"直接给答案"的照样是要走，不是要学', () => {
    expect(detectTutorIntent('别问了，直接把第一问的答案给我')).not.toBe('enter');
  });

  it('不误伤：普通画图请求不该被当成求辅导', () => {
    expect(detectTutorIntent('帮我从左边开始画一排方块')).not.toBe('enter');
  });
});
