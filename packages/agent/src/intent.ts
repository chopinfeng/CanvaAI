/**
 * 从用户的话里识别「他想被教」还是「他想要答案」。
 *
 * 为什么需要：辅导模式的开关藏在面板角落，而用户的自然表达就是
 * 「给我讲这道题」。指望他先找到开关再提问，等于这个模式不存在。
 *
 * 只认**明确**的信号，宁可漏判也不误判：
 * 误判成辅导模式的代价是用户想要个答案却被反问一路，比多点一次开关烦得多。
 * 所以「讲讲这个流程图」不进辅导（那是协作画图），「讲讲这道题」才进。
 */

export type TutorIntent = 'enter' | 'exit' | 'switch' | null;

/** 想被一步步教 */
const ENTER = [
  /讲(讲|一下|下)?(这|那)?[道条]?题/,          // 给我讲这道题 / 讲讲题
  /(这|那)[道条]题.{0,4}(怎么|如何)(做|解|算|写)/, // 这道题怎么做
  // "带着我一步步做" —— 带和我之间会插"着/上"，别把它卡死
  /(教|带)(着|上)?我.{0,8}(做|解|算|学|题|来)/,
  /辅导|循序渐进/,
  // "一步步做/走/来/看"都是同一个意思，早先只认"教/讲/来"，
  // 演练里学生说"您带着我一步步做吧"就没识别出来，整场辅导没起来
  /一步[一 、]*步.{0,4}(教|讲|来|做|解|算|走|看|想)/,
  /(我)?(不会|不懂|看不懂|没思路|卡住)/,
  /引导我|考考我|提示我/,

  // 拿着一份被扣分的作答来问——这是最真实的求辅导场景之一，
  // 早先没覆盖：演练里学生说"我写了但被扣了4分，我哪里错了？"，
  // 辅导根本没启动，直接被讲了答案。
  /(哪里|哪儿|哪一步|什么地方).{0,4}(错|不对|有问题)/,
  /错在(哪|哪里|哪儿|哪一步)/,
  /为什么.{0,6}(错|不对|扣分|扣了)/,
  /扣了?\s*\d*\s*分/,
  /(看看|检查|批).{0,4}(我的)?(作答|解答|解法|过程|步骤|答案对不对)/,
];

/** 不学了，去干别的 —— 和「要答案」是两回事，说法也不一样 */
const SWITCH = [
  /(先)?不(学|做|讲|练)了/,
  /(换|说)个话题|聊点别的|先做别的|先放一放|待会儿?再(学|说|做)/,
  /(我们)?(先|来|开始)?(帮我)?(画|设计|做)(个|一个|一张|张)?(图|流程图|架构图|方案|草图|房子|画)/,
  /不用管(这道?题|它)了?/,
];

/** 不想被绕，直接要结果 */
const EXIT = [
  // 「直接告诉我这道题的答案」中间还会插一截，别把间隔卡太死
  /直接(告诉|说|给)我?.{0,8}答案/,
  /(把)?答案(直接)?(告诉|给)我/,
  /别(问|绕|讲|说)了|不用(引导|提示|问)/,
  /直接(说|讲|做|算)(结果|出来|完)/,
  /退出辅导|关掉辅导|不用辅导/,
];

export function detectTutorIntent(text: string): TutorIntent {
  const t = text.trim();
  if (!t) return null;
  // 先判离开：用户说"别问了直接给答案"时，句子里往往同时带着"讲/题"
  if (EXIT.some((re) => re.test(t))) return 'exit';
  if (SWITCH.some((re) => re.test(t))) return 'switch';
  if (ENTER.some((re) => re.test(t))) return 'enter';
  return null;
}
